#!/usr/bin/env python3
"""生成《大学生创业实训平台·系统操作手册》（教师/学生，不含管理端）"""

from pathlib import Path

from docx import Document
from docx.enum.text import WD_LINE_SPACING
from docx.oxml.ns import qn
from docx.shared import Pt, Cm

OUT = Path(__file__).resolve().parent / "系统操作手册.docx"


def set_doc_style(doc: Document) -> None:
    style = doc.styles["Normal"]
    style.font.name = "宋体"
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    style.font.size = Pt(11)
    pf = style.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.25
    pf.space_after = Pt(6)


def h(doc: Document, text: str, level: int) -> None:
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        run.font.name = "黑体"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")


def p(doc: Document, text: str) -> None:
    doc.add_paragraph(text)


def steps(doc: Document, items: list[str]) -> None:
    for i, text in enumerate(items, 1):
        doc.add_paragraph(f"{i}. {text}", style="List Number")


def bullets(doc: Document, items: list[str]) -> None:
    for text in items:
        doc.add_paragraph(text, style="List Bullet")


def build() -> Document:
    doc = Document()
    set_doc_style(doc)
    sec = doc.sections[0]
    sec.top_margin = Cm(2.5)
    sec.bottom_margin = Cm(2.5)
    sec.left_margin = Cm(2.8)
    sec.right_margin = Cm(2.8)

    title = doc.add_paragraph()
    title.alignment = 1
    r = title.add_run("大学生创业实训平台\n系统操作手册")
    r.bold = True
    r.font.size = Pt(22)
    r.font.name = "黑体"
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")

    sub = doc.add_paragraph()
    sub.alignment = 1
    s = sub.add_run("（教师端 · 学生端）")
    s.font.size = Pt(14)

    p(
        doc,
        "本文档依据《实训平台项目设计方案》与《演示系统业务说明》编写，描述教师、学生在平台上的标准操作流程。"
        "不含管理后台（用户治理、平台级课程资源、系统配置等由学校运维人员使用）。",
    )

    h(doc, "一、平台概述", 1)
    p(
        doc,
        "平台面向高校创新创业实训课：学生组队完成从创意、调研、产品、商业模式到计划书的全流程；"
        "教师负责班级组织、课程节奏、过程监控、成果审核与教学评价。",
    )
    p(doc, "建议教学主线（可由教师按校历调整）：")
    bullets(
        doc,
        [
            "学生加入教学班 → 学习实践课程并通过知识点检测",
            "组队与团队确认 → 创新思维与创意生成 → 市场调研与用户画像",
            "产品设计与迭代 → 商业模式设计 → AI 仿真模拟",
            "商业计划书要点撰写与提交 → 教师审核与教学评价",
        ],
    )

    h(doc, "二、学生操作指南", 1)

    h(doc, "2.1 登录与选择教学班", 2)
    steps(
        doc,
        [
            "打开平台首页，使用学校分配的学生账号与密码登录。",
            "登录成功后进入「学生工作台」。若尚未被教师加入任何「个性化教学班」，页面会提示无法开展实训，请联系任课教师。",
            "若同时加入多个教学班，在页面右上角「班级切换器」中选择当前要学习的班级；通知、待办、课程与实训进度均按当前班级加载。",
            "若提示「班级暂未开放」，多为未到教师设置的组队或阶段开始时间，请查看说明或联系教师。",
        ],
    )

    h(doc, "2.2 进度看板", 2)
    steps(
        doc,
        [
            "在学生工作台侧栏打开「进度看板」，查看本团队项目整体完成度与各阶段状态。",
            "在「通知」中查看教师全员通知、学习督促、资源推送及系统消息；可标记已读，任务类通知可跳转待办。",
            "在「待办任务」中处理教师发布的实训任务：查看截止时间、优先级、教师附件；学习达标后按要求完成并提交反馈附件（若教师要求）。",
        ],
    )
    bullets(
        doc,
        [
            "通知侧重告知与提醒；待办任务侧重需完成并提交的成果。",
            "临近截止的紧急任务请优先处理。",
        ],
    )

    h(doc, "2.3 实践课程与知识点检测", 2)
    steps(
        doc,
        [
            "侧栏进入「实践课程」，按章节学习教师配置的视频、文档等资源，系统记录各小节学习进度。",
            "对配置了知识点的章节，需将对应小节学习进度达到要求（通常约 80%）后，方可参加「知识点检测」。",
            "检测通过后记入学习档案，并常作为后续实训模块或教师实训任务的前置条件。",
            "建议先完成本阶段课程与检测，再进入实训模块；未达标时任务「去完成」可能无法打开详情。",
        ],
    )

    h(doc, "2.4 实训模块（按阶段）", 2)
    p(
        doc,
        "侧栏「实训模块」按教学阶段排列。未到开始日期或未完成前置条件时，阶段呈锁定状态，点击可查看开放时间与解锁说明。"
        "组队完成后，队长与队员在不同环节的上传职责可能不同，以页面说明为准。",
    )

    modules = [
        (
            "2.4.1 组队与团队管理",
            [
                "首次进入须回答教师预设的组队问题，系统据此进行 AI 分析并推荐团队角色，请认真作答。",
                "按页面指引完成组队测评等要求后，创建或加入团队，等待教师确认组队结果。",
                "组队经教师确认后，方可解锁后续创意等阶段；团队内请及时沟通分工与材料上传。",
            ],
        ),
        (
            "2.4.2 创新思维与创意生成",
            [
                "学习创新方法（如头脑风暴、SCAMPER 等），与队员协作记录多个创意方案。",
                "按教师要求筛选、完善创意，形成可提交的选题或创意报告材料。",
                "可使用页面提供的 AI 辅助拓展创意（以教师是否开放为准）。",
            ],
        ),
        (
            "2.4.3 市场调研与用户画像",
            [
                "制定调研计划，创建或填写调研问卷，跟踪回收情况（若教师启用外链问卷则按指引发放）。",
                "录入或整理调研数据与分析结论，形成用户画像与调研报告要点。",
                "提交阶段成果，等待教师审核或反馈（若本班启用选题/调研审核流程）。",
            ],
        ),
        (
            "2.4.4 产品设计与迭代",
            [
                "梳理功能清单、用户旅程与原型说明，记录产品版本与迭代思路。",
                "按教师要求上传线框、原型或说明文档；部分班级要求计划或选题通过后再深化设计。",
                "可使用 AI 辅助产品结构分析（若已配置）。",
            ],
        ),
        (
            "2.4.5 商业模式设计",
            [
                "填写商业模式画布（客户、价值主张、渠道、收入与成本等）。",
                "完成 SWOT、营销思路、成本测算等教师要求的分析项；可使用研讨或 AI 辅助（以页面功能为准）。",
                "保存并提交本阶段方案，供教师监控与点评。",
            ],
        ),
        (
            "2.4.6 AI 仿真模拟",
            [
                "基于当前项目方案，使用多角色仿真（如挑剔用户、竞争对手、投资人等视角）进行压力测试。",
                "记录对话中的问题、风险与改进建议，并在团队内讨论修订方案。",
                "将仿真结论用于完善后续商业计划书内容。",
            ],
        ),
        (
            "2.4.7 商业计划书要点",
            [
                "按章节整理前述各阶段成果，撰写商业计划书要点正文。",
                "上传计划书附件、路演 PPT 等教师要求的文件。",
                "提交教师审核，根据审核意见修改后再次提交（若教师允许多轮）。",
            ],
        ),
    ]
    for title_m, st in modules:
        h(doc, title_m, 3)
        steps(doc, st)

    h(doc, "2.5 查看教学评价", 2)
    steps(
        doc,
        [
            "在教师完成评价后，于学生工作台相关入口或「学习档案」查看阶段评价、综合得分与文字反馈。",
            "根据反馈与复盘建议改进后续提交；具体入口以当前版本页面为准。",
        ],
    )

    h(doc, "三、教师操作指南", 1)

    h(doc, "3.1 登录与工作台", 2)
    steps(
        doc,
        [
            "使用教师账号登录，进入「教师工作台」。",
            "熟悉侧栏分组：「班级与学生」「课程建设」「教学监控」「任务与审核」等。",
            "涉及本班数据的功能（引导、组队、审核、课程设置等），请先在右上角选择当前「个性化教学班」。",
            "「全局项目监控」可不选班查看跨班团队列表；与班级强相关的操作务必先选班。",
        ],
    )

    h(doc, "3.2 班级与学生管理", 2)
    steps(
        doc,
        [
            "侧栏进入「班级管理」，新建或维护「个性化教学班」基本信息。",
            "通过「添加学生」按学院、专业、行政班浏览学生池，将学生加入本班；可跨学院、跨专业组班。",
            "保存名册后，在右上角切换到该班，再使用引导、审核等功能。",
        ],
    )

    h(doc, "3.3 课程设置", 2)
    steps(
        doc,
        [
            "在「课程建设」中打开「课程设置」（须已选教学班）。",
            "为各实训阶段配置开始时间、截止时间，与校历、教学周次对齐；未到开始时间学生端对应阶段锁定。",
            "维护与本班相关的评分权重、可见性等参数（以页面提供的配置项为准）。",
            "修改设置后提醒学生刷新学生工作台查看更新；实训任务中的模块名称应与课程环节一致。",
        ],
    )
    p(doc, "说明：全校级知识点库、案例库等平台资源由学校运维在管理端维护；教师以本班设置与任务发布为主。")

    h(doc, "3.4 全局项目监控", 2)
    steps(
        doc,
        [
            "打开「全局项目监控」，按状态、关键词筛选团队。",
            "点击团队卡片查看成员与各阶段进展，通过状态标签识别正常、预警、滞后团队。",
            "对需关注的团队使用「立即干预」，跳转至「动态引导工具」并预选该小组。",
        ],
    )

    h(doc, "3.5 动态引导工具", 2)
    steps(
        doc,
        [
            "选择引导方式：全员通知、一对一引导、学习资源推送、学习督促、实训任务发布；对象可为全班、指定小组或学生。",
            "发布「学习督促」时可设置补学截止时间；学生在通知中收到提醒。",
            "发布「实训任务」时设置关联模块、截止时间、优先级；可上传教师附件，并可要求学生提交反馈附件。",
            "在「效果统计」「历史记录」中查看触达与任务概况；可对未过期记录撤回或删除（过期项删除前会先撤回学生端展示）。",
            "对要求反馈附件的任务，在历史记录「详情」中查看学生提交与下载附件。",
        ],
    )
    bullets(
        doc,
        [
            "学生须完成对应实践课程进度及知识点检测后，方可正常进行关联的实训任务。",
            "资源推送可附带附件，学生在学生中心通知中查看与下载。",
        ],
    )

    h(doc, "3.6 组队管理", 2)
    steps(
        doc,
        [
            "在「任务与审核」中打开「组队管理」，查看本班团队组建情况。",
            "维护或确认「组队预设问题」，供学生首次进入组队流程作答与 AI 角色推荐。",
            "确认或调整组队结果，使学生端解锁后续实训阶段。",
        ],
    )

    h(doc, "3.7 选题审核", 2)
    steps(
        doc,
        [
            "打开「选题审核」，查看各团队提交的选题或创意方案。",
            "给出通过、退回或修改意见；意见应具体明确，便于学生修改后再次提交。",
            "审核中发现共性问题，可通过动态引导工具发送通知或督促。",
        ],
    )

    h(doc, "3.8 商业计划书审核", 2)
    steps(
        doc,
        [
            "打开「商业计划书审核」，查看团队提交的计划书内容与附件。",
            "在线评阅并填写审核意见，必要时要求学生补充材料或修改后重提。",
        ],
    )

    h(doc, "3.9 教学评价", 2)
    steps(
        doc,
        [
            "在「教学评价」中按团队查看过程与成果完成情况。",
            "依据课程量规（过程分、成果分、协作分等权重）录入或调整评分。",
            "填写反馈建议，学生端可查看评价结果；支持按班批量处理（以页面功能为准）。",
        ],
    )

    h(doc, "四、建议开课流程（教师）", 1)
    steps(
        doc,
        [
            "创建个性化教学班并添加学生。",
            "在「课程设置」中配置各实训阶段开始、截止时间。",
            "在「组队管理」中确认组队预设题目。",
            "阶段开放后，通过「全局项目监控」与「动态引导工具」发布任务、督促与资源。",
            "在组队、选题、商业计划书等环节完成审核。",
            "课程结束后在「教学评价」中完成评分与反馈。",
        ],
    )

    h(doc, "五、常见问题", 1)
    faqs = [
        ("学生无法进入某实训阶段？", "检查课程设置中该阶段是否已到开始时间；是否已完成组队确认、选题通过等前置条件。"),
        ("学生无法打开实训任务？", "确认实践课程小节进度与知识点检测是否达标；任务是否已过期或被教师撤回。"),
        ("教师页提示请先选择班级？", "在右上角选择教学班后再进入引导、组队、审核、课程设置。"),
        ("学生看不到最新任务或通知？", "确认学生已切换到正确教学班；教师发布后让学生刷新进度看板。"),
    ]
    for q, a in faqs:
        p(doc, f"问：{q}")
        p(doc, f"答：{a}")

    p(doc, "")
    p(doc, "文档版本：与平台 PRD 及学生/教师工作台功能对齐；界面微调时以实际上线页面为准。")

    return doc


def main() -> None:
    doc = build()
    doc.save(OUT)
    print(f"已生成: {OUT}")


if __name__ == "__main__":
    main()
